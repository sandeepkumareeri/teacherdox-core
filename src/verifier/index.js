'use strict';
// Verifier entry points.
//   verify(input, registry)     reference implementation (node:crypto)
//   verifyWeb(input, registry)  WebCrypto implementation — what the public verifier page runs
//   buildBrowserBundle()        the single script the page loads (no build tools)

const fs = require('node:fs');
const path = require('node:path');
const tdx = require('../tdx');
const web = require('./webverify');
const { verifyBundle, collect, referenceImpl } = require('./report');

const verify = (input, registry) => verifyBundle(input, registry, referenceImpl(tdx));
const verifyWeb = (input, registry) => verifyBundle(input, registry, web);

// Modules the browser bundle contains, keyed by the exact require() strings they use.
const ROOT = path.join(__dirname, '../..');
const BROWSER_MODULES = [
  ['../tdx/canonical', 'src/tdx/canonical.js'],
  ['../tdx/codes', 'src/tdx/codes.js'],
  ['../../spec/schema/tdx-2.0.schema.json', 'spec/schema/tdx-2.0.schema.json'],
  ['../tdx/schema', 'src/tdx/schema.js'],
  ['./webverify', 'src/verifier/webverify.js'],
  ['./report', 'src/verifier/report.js'],
];

/** One self-contained script defining window.tdxVerify = { verify(input, registry), ...webverify }. */
function buildBrowserBundle() {
  const defs = BROWSER_MODULES.map(([name, file]) => {
    const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    const body = file.endsWith('.json') ? `module.exports = ${src.trim()};` : src;
    return `defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${body}\n};`;
  }).join('\n');
  return `/* .tdx verifier for browsers — generated by \`npm run build:verifier\` from src/verifier and src/tdx. Do not edit. Apache-2.0. */
(function () {
'use strict';
var defs = {}, cache = {};
function load(name) {
  if (cache[name]) return cache[name].exports;
  if (!defs[name]) throw new Error('tdx-verify bundle: missing module ' + name);
  var module = cache[name] = { exports: {} };
  defs[name](module, module.exports, load);
  return module.exports;
}
${defs}
var web = load('./webverify'), report = load('./report');
var api = Object.assign({}, web, { collect: report.collect, verify: function (input, registry) { return report.verifyBundle(input, registry, web); } });
if (typeof window !== 'undefined') window.tdxVerify = api;
if (typeof module !== 'undefined' && module.exports) module.exports = api;
})();
`;
}

module.exports = { verify, verifyWeb, verifyBundle, collect, buildBrowserBundle, web };
